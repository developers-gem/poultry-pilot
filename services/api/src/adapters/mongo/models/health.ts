import { ADMINISTRATION_ROUTES, HEALTH_RECORD_TYPES, MEDICINE_TYPES, STOCK_UNITS, VACCINATION_STATUSES } from "@poultrypilot/constants";
import { Schema } from "mongoose";
import { LIVE, SourceSchema, bool, defineCollection, enumOf, int, localDate, money, num, ref, str, text } from "./base.js";

const D = "Health";

export const MedicineModel = defineCollection({
  model: "Medicine",
  collection: "medicines",
  domain: D,
  ownership: "farm",
  description:
    "Catalog of vaccines and medicines the farm uses, with withdrawal periods. Clinical facts only; stock lives in inventory_items.",
  fields: {
    name: str({ required: true, max: 120 }),
    type: enumOf(MEDICINE_TYPES, { required: true }),
    activeIngredient: str({ max: 200 }),
    manufacturer: str({ max: 120 }),
    defaultRoute: enumOf(ADMINISTRATION_ROUTES),
    doseUnit: enumOf(STOCK_UNITS),
    /** Days after the last dose before birds may be sold for meat. */
    withdrawalMeatDays: int({ max: 365 }),
    /** Days after the last dose before eggs may be sold. */
    withdrawalEggDays: int({ max: 365 }),
    prescriptionRequired: bool(false),
    label: { type: SourceSchema },
    notes: text(1000),
  },
  indexes: [{ fields: { farmId: 1, name: 1 }, options: { unique: true, ...LIVE }, why: "Medicine picker (prefix); names unique within a farm" }],
});

const TreatmentSchema = new Schema(
  {
    medicineId: ref("Medicine", { required: true }),
    dose: num(),
    doseUnit: enumOf(STOCK_UNITS),
    route: enumOf(ADMINISTRATION_ROUTES),
    startDate: localDate({ required: true }),
    endDate: localDate(),
    /** Derived from endDate + medicine withdrawal days when saved; blocks bird/egg sales until passed. */
    withdrawalMeatUntil: localDate(),
    withdrawalEggsUntil: localDate(),
    prescribedBy: str({ max: 120 }),
  },
  { _id: false },
);

export const HealthRecordModel = defineCollection({
  model: "HealthRecord",
  collection: "health_records",
  domain: D,
  ownership: "farm",
  description:
    "Vet visits, observations, treatments, lab tests and post-mortems. Records what people observed and what a vet concluded; PoultryPilot never diagnoses.",
  fields: {
    flockId: ref("Flock"),
    houseId: ref("House"),
    type: enumOf(HEALTH_RECORD_TYPES, { required: true }),
    date: localDate({ required: true }),
    title: str({ required: true, max: 200 }),
    observedSigns: text(2000),
    affectedBirds: int(),
    vetName: str({ max: 120 }),
    vetUserId: ref("User"),
    /** Entered and attributed to the vet (vetName/vetUserId). Never generated by the system. */
    diagnosisByVet: text(2000),
    lab: { type: new Schema({ name: str({ max: 120 }), reference: str({ max: 60 }), result: text(4000) }, { _id: false }) },
    treatment: { type: TreatmentSchema },
    cost: money(),
    expenseId: ref("Expense"),
    attachments: { type: [new Schema({ name: str({ max: 200 }), assetUrl: str({ required: true, max: 1000 }) }, { _id: false })], default: undefined },
    followUpDate: localDate(),
  },
  indexes: [
    { fields: { farmId: 1, flockId: 1, date: -1 }, why: "Flock health history; active withdrawal check before a sale" },
    { fields: { farmId: 1, date: -1 }, why: "Farm-wide health log for vets and managers" },
  ],
});

export const VaccinationModel = defineCollection({
  model: "Vaccination",
  collection: "vaccinations",
  domain: D,
  ownership: "farm",
  description: "A scheduled vaccination for a flock and, once given, its administration details. Overdue = scheduled and past due (derived).",
  fields: {
    flockId: ref("Flock", { required: true }),
    medicineId: ref("Medicine"),
    vaccineName: str({ required: true, max: 120 }),
    targetDisease: str({ max: 120 }),
    programmeName: str({ max: 120 }),
    status: enumOf(VACCINATION_STATUSES, { required: true, default: "scheduled" }),
    dueDate: localDate({ required: true }),
    administeredDate: localDate(),
    administeredBy: ref("User"),
    route: enumOf(ADMINISTRATION_ROUTES),
    dose: num(),
    doseUnit: enumOf(STOCK_UNITS),
    birdsVaccinated: int(),
    lotNumber: str({ max: 60 }),
    expiryDate: localDate(),
    inventoryTransactionId: ref("InventoryTransaction"),
    skipReason: text(500),
    notes: text(1000),
  },
  indexes: [
    { fields: { farmId: 1, status: 1, dueDate: 1 }, why: "Upcoming and overdue vaccinations across the farm (calendar, reminder job)" },
    { fields: { farmId: 1, flockId: 1, dueDate: 1 }, why: "A flock's vaccination programme" },
  ],
});
