import { existsSync } from "node:fs";
import { resolve } from "node:path";
import ExcelJS from "exceljs";
import PDFDocument from "pdfkit";
import { formatCell, safeText, sheetValue, type Cell, type ReportDocument, type ReportTable } from "../domain/report.js";

// ---- CSV -----------------------------------------------------------------------------

const csvCell = (v: Cell): string => {
  if (v === null || v === undefined) return "";
  if (typeof v === "number") return String(v);
  const s = safeText(v);
  return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};

/**
 * One CSV with the report header and each section as a block (title row, header row, data). UTF-8 with a byte-order
 * mark so spreadsheet programs read non-English text correctly. Money is a plain number in the farm currency.
 */
export function renderCsv(doc: ReportDocument): Buffer {
  const lines: string[] = [];
  const row = (cells: Cell[]) => lines.push(cells.map(csvCell).join(","));
  row([doc.title]);
  row(["Farm", doc.farmName]);
  if (doc.period) row(["Period", `${doc.period.from} to ${doc.period.to}`]);
  row(["Generated", doc.generatedAt]);
  row(["Generated by", doc.generatedBy]);
  row(["Currency", doc.currency]);
  for (const s of doc.sections) {
    lines.push("");
    row([s.title]);
    if (s.kind === "summary") {
      for (const it of s.items) row([it.label, sheetValue(it.value, it.type)]);
    } else {
      row(s.columns.map((c) => (c.type === "money" ? `${c.label} (${doc.currency})` : c.type === "percent" ? `${c.label} (%)` : c.label)));
      for (const r of s.rows) row(s.columns.map((c) => sheetValue(r[c.key] ?? null, c.type)));
      if (s.totals) row(s.columns.map((c, i) => (i === 0 && s.totals![c.key] === undefined ? "Total" : sheetValue(s.totals![c.key] ?? null, c.type))));
    }
  }
  if (doc.notes.length) {
    lines.push("");
    row(["Notes"]);
    for (const n of doc.notes) row([n]);
  }
  return Buffer.concat([Buffer.from([0xef, 0xbb, 0xbf]), Buffer.from(lines.join("\r\n") + "\r\n", "utf8")]);
}

