/** DejaVu Sans is bundled (assets/fonts) for wide character coverage; Helvetica is the fallback. */
function fontPaths(): { regular: string; bold: string } | null {
  const candidates = [resolve(process.cwd(), "assets/fonts"), resolve(process.cwd(), "services/api/assets/fonts"), process.env["FONT_DIR"] ?? ""].filter(Boolean);
  for (const dir of candidates) {
    const regular = resolve(dir, "DejaVuSans.ttf");
    const bold = resolve(dir, "DejaVuSans-Bold.ttf");
    if (existsSync(regular) && existsSync(bold)) return { regular, bold };
  }
  return null;
}

/** A4 portrait: header, summaries, tables that repeat their header across pages, notes, and "page n of m". */
export function renderPdf(doc: ReportDocument): Promise<Buffer> {
  return new Promise((resolvePdf, reject) => {
    const pdf = new PDFDocument({ size: "A4", margin: 40, bufferPages: true, info: { Title: doc.title, Author: "PoultryPilot", Subject: doc.farmName } });
    const chunks: Buffer[] = [];
    pdf.on("data", (c: Buffer) => chunks.push(c));
    pdf.on("end", () => resolvePdf(Buffer.concat(chunks)));
    pdf.on("error", reject);
    const fonts = fontPaths();
    if (fonts) {
      pdf.registerFont("body", fonts.regular);
      pdf.registerFont("bold", fonts.bold);
    }
    const body = fonts ? "body" : "Helvetica";
    const bold = fonts ? "bold" : "Helvetica-Bold";
    const left = pdf.page.margins.left;
    const width = pdf.page.width - pdf.page.margins.left - pdf.page.margins.right;
    const bottom = () => pdf.page.height - pdf.page.margins.bottom - 20;
    const ensure = (h: number) => {
      if (pdf.y + h > bottom()) pdf.addPage();
    };

    pdf.font(bold).fontSize(18).text(doc.title);
    pdf.font(body).fontSize(10).fillColor("#444").text(`${doc.farmName}${doc.period ? `  ·  ${doc.period.from} to ${doc.period.to}` : ""}`);
    pdf.text(`Generated ${doc.generatedAt.replace("T", " ").slice(0, 16)} UTC by ${doc.generatedBy}  ·  Amounts in ${doc.currency}`).fillColor("black");
    pdf.moveDown();

    for (const s of doc.sections) {
      ensure(40);
      pdf.font(bold).fontSize(12).text(s.title, left);
      pdf.moveDown(0.3);
      if (s.kind === "summary") {
        pdf.fontSize(9);
        for (const it of s.items) {
          ensure(14);
          const y = pdf.y;
          pdf.font(body).text(it.label, left, y, { width: width * 0.55 });
          pdf.font(bold).text(formatCell(it.value, it.type, doc.currency, it.decimals), left + width * 0.55, y, { width: width * 0.45, align: "right" });
          pdf.y = Math.max(pdf.y, y + 12);
        }
        pdf.moveDown(0.8);
        continue;
      }
      // Table: widths by column type, text columns share the remaining space.
      const fixed = (t: string) => (t === "text" ? 0 : t === "date" ? 62 : t === "money" ? 78 : 54);
      const fixedTotal = s.columns.reduce((t, c) => t + fixed(c.type), 0);
      const textCols = s.columns.filter((c) => c.type === "text").length;
      const free = Math.max(60, width - fixedTotal);
      const widths = s.columns.map((c) => (c.type === "text" ? free / Math.max(1, textCols) : fixed(c.type)));
      const scale = Math.min(1, width / widths.reduce((t, w) => t + w, 0));
      const w = widths.map((x) => x * scale);
      const rowH = 14;
      const header = () => {
        ensure(rowH * 2);
        const y = pdf.y;
        pdf.rect(left, y - 2, width, rowH).fill("#e8ece8").fillColor("black");
        let x = left;
        pdf.font(bold).fontSize(7.5);
        s.columns.forEach((c, i) => {
          pdf.text(c.label, x + 2, y + 1, { width: w[i]! - 4, align: c.type === "text" || c.type === "date" ? "left" : "right", lineBreak: false, ellipsis: true });
          x += w[i]!;
        });
        pdf.y = y + rowH;
      };
      header();
      const line = (r: Record<string, Cell>, isTotal: boolean, shade: boolean) => {
        if (pdf.y + rowH > bottom()) {
          pdf.addPage();
          header();
        }
        const y = pdf.y;
        if (shade) pdf.rect(left, y - 2, width, rowH).fill("#f6f7f6").fillColor("black");
        let x = left;
        pdf.font(isTotal ? bold : body).fontSize(7.5);
        s.columns.forEach((c, i) => {
          const v = isTotal && i === 0 && r[c.key] === undefined ? "Total" : formatCell(r[c.key] ?? null, c.type, doc.currency, c.decimals);
          pdf.text(v, x + 2, y + 1, { width: w[i]! - 4, align: c.type === "text" || c.type === "date" ? "left" : "right", lineBreak: false, ellipsis: true });
          x += w[i]!;
        });
        pdf.y = y + rowH;
      };
      if (!s.rows.length) pdf.font(body).fontSize(8).fillColor("#666").text("No records in this period.", left).fillColor("black");
      s.rows.forEach((r, i) => line(r, false, i % 2 === 1));
      if (s.totals) line(s.totals, true, false);
      if (s.note) pdf.font(body).fontSize(7.5).fillColor("#555").text(s.note, left, pdf.y + 2, { width }).fillColor("black");
      pdf.moveDown(0.8);
    }
    if (doc.notes.length) {
      ensure(30);
      pdf.font(bold).fontSize(10).text("Notes", left);
      pdf.font(body).fontSize(8);
      for (const n of doc.notes) pdf.text(`• ${n}`, left, pdf.y, { width });
    }
    const range = pdf.bufferedPageRange();
    for (let i = range.start; i < range.start + range.count; i++) {
      pdf.switchToPage(i);
      pdf.font(body).fontSize(7).fillColor("#777").text(`PoultryPilot · ${doc.title} · ${doc.farmName} · page ${i + 1} of ${range.count}`, left, pdf.page.height - pdf.page.margins.bottom + 10, { width, align: "center", lineBreak: false });
    }
    pdf.end();
  });
}

export async function renderReport(doc: ReportDocument, format: "pdf" | "csv" | "xlsx"): Promise<{ bytes: Buffer; contentType: string; extension: string }> {
  if (format === "csv") return { bytes: renderCsv(doc), contentType: "text/csv; charset=utf-8", extension: "csv" };
  if (format === "xlsx") return { bytes: await renderXlsx(doc), contentType: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", extension: "xlsx" };
  return { bytes: await renderPdf(doc), contentType: "application/pdf", extension: "pdf" };
}
