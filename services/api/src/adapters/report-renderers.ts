/** A summary sheet, then one sheet per table with bold frozen headers and real number formats. */
export async function renderXlsx(doc: ReportDocument): Promise<Buffer> {
  const wb = new ExcelJS.Workbook();
  wb.creator = "PoultryPilot";
  wb.created = new Date(doc.generatedAt);
  const used = new Set<string>();
  const sheetName = (t: string) => {
    let base = t.replace(/[[\]:*?/\\]/g, " ").slice(0, 28).trim() || "Sheet";
    let name = base;
    for (let n = 2; used.has(name.toLowerCase()); n++) name = `${base.slice(0, 25)} ${n}`;
    used.add(name.toLowerCase());
    return name;
  };
  const fmt = (type: string, decimals?: number) => (type === "money" ? "#,##0.00" : type === "percent" ? `0.${"0".repeat(decimals ?? 1)}` : type === "number" ? (decimals ? `#,##0.${"0".repeat(decimals)}` : "#,##0.##") : undefined);
  const text = (v: Cell) => (typeof v === "string" ? safeText(v) : v);

  const summary = wb.addWorksheet(sheetName("Summary"));
  summary.columns = [{ width: 34 }, { width: 40 }];
  const meta: [string, Cell][] = [[doc.title, null], ["Farm", doc.farmName], ...(doc.period ? ([["Period", `${doc.period.from} to ${doc.period.to}`]] as [string, Cell][]) : []), ["Generated", doc.generatedAt], ["Generated by", doc.generatedBy], ["Currency", doc.currency]];
  for (const [k, v] of meta) summary.addRow([k, text(v)]);
  summary.getRow(1).font = { bold: true, size: 14 };
  for (const s of doc.sections.filter((x) => x.kind === "summary")) {
    summary.addRow([]);
    summary.addRow([s.title]).font = { bold: true };
    for (const it of s.items) {
      const r = summary.addRow([it.label, text(sheetValue(it.value, it.type))]);
      const f = fmt(it.type, it.decimals);
      if (f && typeof it.value === "number") r.getCell(2).numFmt = f;
    }
  }
  if (doc.notes.length) {
    summary.addRow([]);
    summary.addRow(["Notes"]).font = { bold: true };
    for (const n of doc.notes) summary.addRow([text(n)]);
  }

  for (const t of doc.sections.filter((x): x is ReportTable => x.kind === "table")) {
    const ws = wb.addWorksheet(sheetName(t.title));
    ws.columns = t.columns.map((c) => ({ header: c.type === "money" ? `${c.label} (${doc.currency})` : c.type === "percent" ? `${c.label} (%)` : c.label, key: c.key, width: Math.min(40, Math.max(10, c.label.length + 4)) }));
    ws.getRow(1).font = { bold: true };
    ws.views = [{ state: "frozen", ySplit: 1 }];
    for (const r of t.rows) ws.addRow(Object.fromEntries(t.columns.map((c) => [c.key, text(sheetValue(r[c.key] ?? null, c.type))])));
    if (t.totals) {
      const tr = ws.addRow(Object.fromEntries(t.columns.map((c, i) => [c.key, i === 0 && t.totals![c.key] === undefined ? "Total" : text(sheetValue(t.totals![c.key] ?? null, c.type))])));
      tr.font = { bold: true };
    }
    t.columns.forEach((c, i) => {
      const f = fmt(c.type, c.decimals);
      if (f) ws.getColumn(i + 1).numFmt = f;
    });
    if (t.note) ws.addRow([]).getCell(1).value = text(t.note);
  }
  return Buffer.from(await wb.xlsx.writeBuffer());
}

